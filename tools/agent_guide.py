#!/usr/bin/env python3
"""Build kisi's agent guide for any assistant from the kisi-prepare skill (one source of truth).

Usage: agent_guide.py [--check]

kicad-plugin/agent/KISI-AGENT-GUIDE.md = kicad-plugin/agent/KISI-AGENT-GUIDE.in.md (the parts that differ: how to
run kisi with or without a shell, the report) with its {{steps}} and {{notes}} replaced by the blocks of
claude-plugin/skills/kisi-prepare/SKILL.md between `<!-- agent-guide:<name> begin … -->` and
`<!-- agent-guide:<name> end -->`. Edit those, then run this; --check fails when the committed guide differs
(CI, tools/build_kicad_pcm.py) or when the guide names assistant-specific things (skills, tools).
The KiCad plugin ships the guide (plugins/agent/), and the viewer's agent card offers it.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SKILL = os.path.join(ROOT, "claude-plugin", "skills", "kisi-prepare", "SKILL.md")
TEMPLATE = os.path.join(ROOT, "kicad-plugin", "agent", "KISI-AGENT-GUIDE.in.md")
GUIDE = os.path.join(ROOT, "kicad-plugin", "agent", "KISI-AGENT-GUIDE.md")
# words that belong to one assistant's tooling, not in a guide for any assistant
FORBIDDEN = re.compile(r"\b(skill|skills|Claude|subagent|WebFetch|WebSearch|MCP)\b")


def read(p):
    with open(p, encoding="utf-8") as f:
        return f.read()


def block(skill, name):
    m = re.search(r"<!-- agent-guide:%s begin[^>]*-->\n(.*?)\n<!-- agent-guide:%s end -->" % (name, name), skill, re.S)
    if not m:
        raise SystemExit(f"agent_guide: no block {name!r} in {os.path.relpath(SKILL, ROOT)}")
    return m.group(1).strip("\n")


HEAD = ("<!-- Generated by tools/agent_guide.py from KISI-AGENT-GUIDE.in.md and the kisi-prepare instructions "
        "(claude-plugin/skills/kisi-prepare/SKILL.md) – edit those, not this file. -->\n")


def body():
    skill, tpl = read(SKILL), read(TEMPLATE)
    return re.sub(r"\{\{(\w+)\}\}", lambda m: block(skill, m.group(1)), tpl)


def problems(text):
    bad = [f"assistant-specific word {m.group(0)!r} in line {text[:m.start()].count(chr(10)) + 2}" for m in FORBIDDEN.finditer(text)]
    if "{{" in text:
        bad.append("an unreplaced {{…}}")
    return bad


def main():
    b = body()
    bad, text = problems(b), HEAD + b
    if "--check" in sys.argv:
        cur = read(GUIDE) if os.path.exists(GUIDE) else ""
        if cur != text:
            bad.append(f"{os.path.relpath(GUIDE, ROOT)} is not up to date – run tools/agent_guide.py")
        for b in bad:
            print("PROBLEM:", b)
        print(f"agent guide: {'ok' if not bad else f'{len(bad)} problem(s)'}")
        return 1 if bad else 0
    if bad:
        raise SystemExit("agent_guide: " + "; ".join(bad))
    with open(GUIDE, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"{os.path.relpath(GUIDE, ROOT)}: {len(text)} characters")
    return 0


if __name__ == "__main__":
    sys.exit(main())
