"""kisi-fdtd references too large for one machine, on GitHub Actions runners (TESTS.md section 17).

The cases are cut into tasks (case × excited port), the tasks into shards (fdtd_plan.json); each shard runs on a
4-vCPU runner (workflow `fdtd-refs`), kisi-fdtd with several threads per task. The raw results (one kisi-fdtd JSON
per task, with the runner's CPU and the wall time) go to validation/fdtd/fdtd_raw/<case>/ex<j>_r<refine>.json,
which the workflow commits to its branch; `merge` turns them into validation/via_ref/<case>/ (kisi.sNp,
fields.json, meta.json) exactly as run_refs.py would, the former result kept as kisi_base.sNp (--keep-base).

  plan  CASE[,CASE…] [--refine 2] [--threads 4] [--max-shards 15]   → fdtd_plan.json
  run   --shard K [--exe kisi-fdtd] [--out fdtd_raw]                  one shard (skips tasks already done)
  merge [CASE,…] [--refine 2] [--raw fdtd_raw] [--out ../via_ref] [--keep-base]   raw results → reference files

The mesh is the case's, with the cell at metal ÷ refine (run_refs.metal_refined, openems_refs.py's "fine" mesh
for refine 2).
"""
import argparse, datetime, glob, json, os, shutil, subprocess, sys, tempfile, time

HERE = os.path.dirname(os.path.abspath(__file__))
REF = os.path.join(os.path.dirname(HERE), "via_ref")
PLAN = os.path.join(HERE, "fdtd_plan.json")
RAW = os.path.join(HERE, "fdtd_raw")
sys.path.insert(0, HERE)
import sparam  # noqa: E402
from run_refs import excitation, field_raster, metal_refined  # noqa: E402
from openems_refs import all_cases, host_info  # noqa: E402


def task_case(name, j, refine, threads):
    """the case of one task: refined mesh, one excited port; field monitors only on the first excitation"""
    case = json.load(open(all_cases()[name]))
    c = metal_refined(case, refine)
    ex, _ = excitation(case)
    c["excite"] = [j]
    c["threads"] = threads
    if j != ex[0]:
        c.pop("monitors", None)
    return case, c


def plan(a):
    names = [n for n in a.cases.split(",") if n]
    tasks = []
    for n in names:
        case = json.load(open(all_cases()[n]))
        ex, _ = excitation(case)
        k = json.load(open(os.path.join(REF, n, "meta.json")))["runs"].get("kisi_base") or json.load(open(os.path.join(REF, n, "meta.json")))["runs"]["kisi"]
        for i, j in enumerate(ex):
            # rough cost: cells × steps grow with the refinement (cells ≈ refine^1.6, steps ≈ refine)
            est = k["cells"] * a.refine ** 1.6 * k["steps"][i] * a.refine
            tasks.append({"case": n, "ex": j, "refine": a.refine, "est_gupd": round(est / 1e9, 1)})
    tasks.sort(key=lambda t: -t["est_gupd"])
    # greedy: the largest tasks alone, the small ones packed so that no shard exceeds the largest task
    nmax = min(a.max_shards, len(tasks))
    shards = [{"tasks": [], "est_gupd": 0.0} for _ in range(nmax)]
    for t in tasks:
        s = min(shards, key=lambda s: s["est_gupd"])
        s["tasks"].append(t)
        s["est_gupd"] = round(s["est_gupd"] + t["est_gupd"], 1)
    shards = [dict(s, threads=a.threads) for s in shards if s["tasks"]]
    json.dump({"note": "generated by fdtd_refs.py plan; est_gupd: rough estimate in 10^9 cell updates", "shards": shards}, open(a.plan, "w"), indent=1)
    print(f"{len(tasks)} tasks in {len(shards)} shards; largest shard {max(s['est_gupd'] for s in shards)} G cell updates")


def run(a):
    sh = json.load(open(a.plan))["shards"][a.shard]
    host = host_info()
    os.makedirs(os.path.join(a.out, "_logs"), exist_ok=True)
    log = open(os.path.join(a.out, "_logs", f"shard{a.shard}.txt"), "a")

    def say(msg):  # the job logs may not be reachable: the log goes with the results
        print(msg, flush=True)
        log.write(f"{datetime.datetime.now().isoformat(timespec='seconds')} {msg}\n")
        log.flush()

    say(f"shard {a.shard}: {len(sh['tasks'])} tasks, {sh['threads']} threads, host {host}")
    for t in sh["tasks"]:
        dst = os.path.join(a.out, t["case"], f"ex{t['ex']}_r{t['refine']:g}.json")
        if os.path.exists(dst):
            say(f"{t['case']} ex{t['ex']}: done")
            continue
        _, c = task_case(t["case"], t["ex"], t["refine"], sh["threads"])
        tmp = tempfile.mkdtemp(prefix="fd_")
        p = os.path.join(tmp, "case.json")
        json.dump(c, open(p, "w"))
        t0 = time.time()
        pr = subprocess.run([a.exe, p], capture_output=True, text=True)
        if pr.returncode:
            say(f"{t['case']} ex{t['ex']}: FAILED {pr.stderr[-1500:]}")
            continue
        r = json.loads(pr.stdout)
        r.update(refine=t["refine"], dfine=c["mesh"]["dfine"], threads=sh["threads"], wall_s=round(time.time() - t0, 1), host=host)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        json.dump(r, open(dst, "w"), separators=(",", ":"))
        say(f"{t['case']} ex{t['ex']}: {r['cells']} cells, {r['runs'][0]['steps']} steps, {r['wall_s']} s")


def merge(a):
    for d in sorted(glob.glob(os.path.join(a.raw, "*", ""))):
        name = os.path.basename(os.path.dirname(d))
        if name.startswith("_") or (a.cases and name not in a.cases.split(",")):
            continue
        case = json.load(open(all_cases()[name]))
        ex, mirror = excitation(case)
        parts = {}
        for j in ex:
            p = os.path.join(d, f"ex{j}_r{a.refine:g}.json")
            if os.path.exists(p):
                parts[j] = json.load(open(p))
        if len(parts) != len(ex):
            print(f"{name}: {len(parts)} of {len(ex)} excitations, skipped")
            continue
        first = parts[ex[0]]
        r = dict(first, runs=[parts[j]["runs"][0] for j in ex])
        n = len(case["ports"])
        f, S = sparam.from_kisi(r, n, mirror)
        k = first["refine"]
        info = {"cells": first["cells"], "steps": [x["steps"] for x in r["runs"]], "dt": first["runs"][0]["dt"],
                "seconds": round(sum(parts[j]["wall_s"] for j in ex), 1), "dfine": first["dfine"], "dmax": case["mesh"].get("dmax"), "refine": k,
                "threads": first["threads"], "runner": "GitHub Actions ubuntu-24.04 (fdtd_refs.py, workflow fdtd-refs)",
                "seconds_per_excitation": [parts[j]["wall_s"] for j in ex], "hosts": [parts[j]["host"] for j in ex]}
        out = os.path.join(a.out, name)
        os.makedirs(out, exist_ok=True)
        old = os.path.join(out, f"kisi.s{n}p")
        mp = os.path.join(out, "meta.json")
        meta = json.load(open(mp)) if os.path.exists(mp) else {"case": name, "fmax": case["fmax"], "tool": "kisi-fdtd (conformal metal, CPML)", "runs": {}}
        if a.keep_base and os.path.exists(old) and not os.path.exists(os.path.join(out, f"kisi_base.s{n}p")):
            shutil.copy(old, os.path.join(out, f"kisi_base.s{n}p"))
            meta["runs"]["kisi_base"] = dict(meta["runs"]["kisi"], date=meta.get("date"), file=f"kisi_base.s{n}p")
        hdr = [f"{name}: {case['meta']['title']}", f"stackup: {case['meta']['stackup_title']}", "ports: " + ", ".join(p["name"] for p in case["meta"]["ports"])]
        sparam.write_touchstone(old, f, S, hdr + [f"kisi-fdtd, conformal, dfine {info['dfine']} mm (the cell at metal ÷ {k:g}), {info['cells']} cells"],
                                case["ports"][0].get("r", 50.0))
        fr = field_raster(case, r)
        if fr:
            json.dump(fr, open(os.path.join(out, "fields.json"), "w"), separators=(",", ":"))
        meta["meta"] = dict(case["meta"], ref_refine=k)
        meta["date"] = datetime.date.today().isoformat()
        meta["runs"] = {"kisi": info, **{x: v for x, v in meta["runs"].items() if x != "kisi"}}
        json.dump(meta, open(mp, "w"), indent=1)
        print(f"{name}: {info['cells']} cells, steps {info['steps']}, {info['seconds']} s on {info['hosts'][0].get('model')}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["plan", "run", "merge"])
    ap.add_argument("cases", nargs="?", default="")
    ap.add_argument("--plan", default=PLAN)
    ap.add_argument("--refine", type=float, default=2.0)
    ap.add_argument("--threads", type=int, default=4)
    ap.add_argument("--max-shards", type=int, default=15)
    ap.add_argument("--shard", type=int, default=0)
    ap.add_argument("--exe", default=os.environ.get("KISI_FDTD", "kisi-fdtd"))
    ap.add_argument("--out", default=None)
    ap.add_argument("--raw", default=RAW)
    ap.add_argument("--keep-base", action="store_true")
    a = ap.parse_args()
    if a.cmd == "plan":
        plan(a)
    elif a.cmd == "run":
        a.out = a.out or RAW
        run(a)
    else:
        a.out = a.out or REF
        merge(a)


if __name__ == "__main__":
    main()
