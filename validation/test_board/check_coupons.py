#!/usr/bin/env python3
"""Run kisi on every coupon board (validation/test_board/README.md, section "kisi check").

For each board in boards/*.manifest.json: `kisi overview`, `kisi config-check`, `kisi check --all`,
`kisi interfaces`, `kisi gaps`, `kisi net` on every coupon signal net, with the native CLI (formula
impedances) and, if given, the Node CLI (kisi.mjs, 2D field solver), and `kisi power --pdn RAIL` on
every PDN rail (VDD_*: the H coupons). Writes boards/<board>.kisi_check.json and the summary
kisi_check.md.

usage: python3 check_coupons.py [--kisi target/release/kisi] [--kisi-mjs dist/kisi.mjs] [--boards NAME,...]
"""
import argparse, datetime, glob, json, os, subprocess

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))


def run(cmd, timeout=900):
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    if r.returncode != 0:
        return {"error": r.stderr.strip()[:400] or f"exit {r.returncode}"}
    try:
        return json.loads(r.stdout)
    except json.JSONDecodeError as e:
        return {"error": f"no JSON: {e}"}


def at(marks, ghz):
    for m in marks or []:
        if abs(m["ghz"] - ghz) < 1e-6:
            return round(m["db"], 2)
    return None


def net_summary(d):
    if "error" in d:
        return {"error": d["error"]}
    s = {"length_mm": round(d.get("length_mm") or 0, 2), "delay_ps": round(d.get("delay_ps") or 0, 1),
         "z": {k: (round(v, 2) if isinstance(v, float) else v) for k, v in (d.get("impedance") or {}).items()},
         "segments": [(x["layer"], round(x["len_mm"], 2), round(x["z_ohm_per_line"], 2) if x["z_ohm_per_line"] else None) for x in d.get("segments", [])],
         "il_db": {g: at(d.get("insertion_loss_db"), g) for g in (5.0, 12.5, 25.0)},
         "rl_worst_db": round(d["return_loss_worst_db"], 1) if d.get("return_loss_worst_db") is not None else None,
         "tdr": {k: (round(v, 1) if isinstance(v, float) else v) for k, v in (d.get("tdr") or {}).items()},
         "vias": [{k: (round(v, 2) if isinstance(v, float) else v) for k, v in x.items()} for x in d.get("via_details", [])],
         "warnings": d.get("warnings", [])}
    mm = d.get("mixed_mode")
    if mm and "error" not in mm:
        s["mixed"] = {"sdd21_db": {g: at(mm.get("sdd21_db"), g) for g in (5.0, 12.5, 25.0)}, "scd21_worst": mm.get("scd21_worst"),
                      "tdr": {k: (round(v, 1) if isinstance(v, float) else v) for k, v in (mm.get("tdr") or {}).items()},
                      "skew_ps": round(mm.get("skew_ps") or 0, 2), "rl_diff_worst_db": round(mm.get("return_loss_diff_worst_db") or 0, 1)}
    xt = d.get("crosstalk") or {}
    if xt.get("aggressors") or xt.get("broadside"):
        s["crosstalk"] = {"next_total": xt.get("next_total"), "fext_total": xt.get("fext_total"),
                          "aggressors": [{k: a.get(k) for k in ("net", "next", "fext", "source", "coupled_mm")} for a in xt.get("aggressors", [])],
                          "broadside": len(xt.get("broadside") or [])}
    return s


def pdn_summary(d, rail):
    """the per-IC PDN result of `power --pdn` for the coupon's pin field (U) and its capacitor"""
    if "error" in d:
        return {"error": d["error"]}
    p = (d.get("pdn") or {})
    pi = p.get("per_ic") or {}
    ics = pi.get("ics") or []
    if not ics:
        return {"error": "no per-IC result", "warnings": pi.get("warnings")}
    ic = ics[0]
    caps = ic.get("capacitors_most_effective") or []
    return {"ic": ic.get("ic"), "pins": ic.get("pins"), "z_ohm": {k: round(v, 4) for k, v in (ic.get("z_ohm") or {}).items()},
            "caps": [{k: c.get(k) for k in ("ref", "dist_mm", "l_path_nh", "l_total_nh", "srf_mhz")} for c in caps],
            "anti_resonances": [{"mhz": round(a["hz"] / 1e6, 1), "z_ohm": round(a["z_ohm"], 3)} for a in ic.get("anti_resonances", [])],
            "cavity_first_resonance_mhz": round((p.get("cavity_first_resonance_hz") or 0) / 1e6, 1),
            "capacitor_flags": pi.get("capacitor_flags"), "warnings": pi.get("warnings")}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--kisi", default=os.path.join(REPO, "target", "release", "kisi"))
    ap.add_argument("--kisi-mjs", default=os.path.join(REPO, "dist", "kisi.mjs"))
    ap.add_argument("--boards", default="")
    a = ap.parse_args()
    nat = [a.kisi]
    fld = ["node", a.kisi_mjs] if os.path.exists(a.kisi_mjs) else None
    md = [f"# kisi check of the coupon boards", "",
          f"Generated by `check_coupons.py` on {datetime.date.today().isoformat()}: native `kisi` (formula impedances)"
          + (f" and `kisi.mjs` (2D field solver, file date {datetime.date.fromtimestamp(os.path.getmtime(a.kisi_mjs)).isoformat()})" if fld else "") + ".",
          "Impedances are kisi's per-segment values; a via coupon's net includes the launch (grounded coplanar), the feeds and",
          "the via. DRC: README section 13.", ""]
    for mf in sorted(glob.glob(os.path.join(HERE, "boards", "*.manifest.json"))):
        man = json.load(open(mf))
        name = man["board"]
        if a.boards and not any(b in name for b in a.boards.split(",")):
            continue
        pcb = os.path.join(HERE, "boards", man["file"])
        out = {"board": name, "date": datetime.date.today().isoformat(), "native": {}, "field": {}}
        out["native"]["overview"] = run(nat + ["overview", pcb])
        out["native"]["check_all"] = run(nat + ["check", pcb, "--all"])
        out["native"]["interfaces"] = run(nat + ["interfaces", pcb])
        out["native"]["gaps"] = run(nat + ["gaps", pcb])
        if fld:
            out["field"]["overview"] = run(fld + ["overview", pcb, "--field-time", "600"], timeout=1800)
        out["native"]["config_check"] = run(nat + ["config-check", pcb])
        nets, pdn = {}, {}
        for c in man["coupons"]:
            for n in c["nets"]:
                if n.startswith("VDD_"):
                    pdn[n] = {"coupon": c["id"], "native": pdn_summary(run(nat + ["power", pcb, "--pdn", n]), n)}
                    continue
                if n.startswith("CAV_") or n == "GND" or n.endswith("_N"):
                    continue
                e = {"coupon": c["id"], "native": net_summary(run(nat + ["net", pcb, n]))}
                if fld:
                    e["field"] = net_summary(run(fld + ["net", pcb, n], timeout=900))
                nets[n] = e
        out["nets"] = nets
        out["pdn"] = pdn
        json.dump(out, open(os.path.join(HERE, "boards", name + ".kisi_check.json"), "w"), indent=1)
        # markdown summary
        ov = out["native"]["overview"]
        ovf = out["field"].get("overview") or {}
        md += [f"## {name}", "", f"Stackup: {man['stackup_title']}; {len(man['coupons'])} coupons; size {man['size_mm'][0]} × {man['size_mm'][1]} mm.", ""]
        md.append(f"- Parsed: {'yes' if 'error' not in ov else 'NO: ' + ov['error']}; stackup from the file: {ov.get('stackup_from_file')}; "
                  f"board warnings: {ov.get('warnings') or 'none'}; config `{os.path.basename(man['file']).replace('.kicad_pcb', '.kisi.json')}`: "
                  f"{'ok' if (ov.get('config') or {}).get('ok') else (ov.get('config') or {}).get('errors')}.")
        for o, lab in ((ov, "formula"), (ovf, "field solver")):
            for cl in o.get("classes", []):
                md.append(f"- Class {cl['class']} ({lab}): {cl['nets']} nets, {round(100 * cl['within_5pct'], 1)} % of the length within ±5 % of {cl['target_ohm']:g} Ω.")
        cc = out["native"]["config_check"]
        md.append(f"- `config-check`: {'error: ' + cc['error'][:120] if 'error' in cc else ('ok' if cc.get('ok', not cc.get('errors')) else cc.get('errors'))}"
                  f"{'; warnings: ' + '; '.join(map(str, cc.get('warnings'))) if cc.get('warnings') else ''}.")
        ch = out["native"]["check_all"]
        nlanes = sum(len(b.get("lanes", [])) for b in out["native"]["interfaces"].get("buses", []))
        md.append(f"- `check --all`: {len(ch.get('rows', []))} rows (summary {ch.get('summary')}); `interfaces` lists {nlanes} lanes, all "
                  f"connector–connector; the coupons are judged with `net` below.")
        g = out["native"]["gaps"]
        if "error" not in g:
            items = [x.get("topic") or x.get("what") or x.get("id") for x in (g.get("gaps") or g.get("items") or [])] if isinstance(g, dict) else []
            md.append(f"- `gaps`: {', '.join(str(i) for i in items if i) or json.dumps(g)[:300]}")
        md += ["", "| net | coupon | Z formula mean / min / max (Ω) | Z field mean / min / max (Ω) | via: Z (Ω), return path, model | TDR 35 ps min / max (Ω) | IL 5 / 12.5 / 25 GHz (dB) | warnings |",
               "|---|---|---|---|---|---|---|---|"]
        for n, e in nets.items():
            s, f = e["native"], e.get("field") or {}
            if "error" in s:
                md.append(f"| {n} | {e['coupon']} | error: {s['error'][:80]} | | | | | |")
                continue
            zf = s["z"]
            zd = f.get("z") or {}
            fmt = lambda z: " / ".join(f"{z.get(k):.1f}" if isinstance(z.get(k), (int, float)) else "–" for k in ("mean", "min", "max"))
            vias = "; ".join(f"{v.get('z_ohm')}, {v.get('return_path')}, {v.get('model')}" + (f", stub {v.get('stub_mm')} mm" if v.get("stub_mm") else "") for v in s["vias"]) or "–"
            tdr = s.get("mixed", {}).get("tdr") or s["tdr"]
            tmin = tdr.get("zdiff_min", tdr.get("z_min"))
            tmax = tdr.get("zdiff_max", tdr.get("z_max"))
            il = s.get("mixed", {}).get("sdd21_db") or s["il_db"]
            md.append(f"| {n} | {e['coupon']} | {fmt(zf)} | {fmt(zd)} | {vias} | {tmin} / {tmax} | {il.get(5.0)} / {il.get(12.5)} / {il.get(25.0)} | {'; '.join(s['warnings'])[:120] or '–'} |")
        if pdn:
            md += ["", "PDN coupons (`power --pdn RAIL`, native; the capacitor populated as in the board file: generic 100 nF X7R, package from the pad pitch,"
                   " ESL / ESR / mounting estimates from `data/components.json` until PI_CAP fields are added):", "",
                   "| rail | coupon | cap distance (mm, IC to cap centre) | L path / L total (nH) | SRF (MHz) | Z 1 / 10 / 100 MHz / 1 GHz (Ω) | first cavity resonance (MHz) | warnings |",
                   "|---|---|---|---|---|---|---|---|"]
            for n, e in pdn.items():
                s = e["native"]
                if "error" in s:
                    md.append(f"| {n} | {e['coupon']} | error: {str(s['error'])[:80]} | | | | | |")
                    continue
                c = (s["caps"] or [{}])[0]
                z = s["z_ohm"]
                warn = [w for w in (s["warnings"] or []) if not w.startswith("no regulator")]
                md.append(f"| {n} | {e['coupon']} | {c.get('dist_mm')} | {c.get('l_path_nh')} / {c.get('l_total_nh')} | {c.get('srf_mhz')} | "
                          f"{z.get('1M')} / {z.get('10M')} / {z.get('100M')} / {z.get('1G')} | {s['cavity_first_resonance_mhz']} | {'; '.join(warn)[:120] or '–'} |")
        md.append("")
        print(name, "done", flush=True)
    open(os.path.join(HERE, "kisi_check.md"), "w").write("\n".join(md) + "\n")


if __name__ == "__main__":
    main()
